#!/bin/sh
if [ "${NXMODULE_COMMON_LOADED:-}" != 1 ]; then . "$(dirname "$0")/lifecycle.sh"; fi

prepare_uninstall() {
    target=$NXMODULE_PANEL_DIR/conf.d/05-nxpanel-geoip2.conf
    missing "$target" && return 0
    safe_file "$target" && [ "$(wc -c < "$target")" -le 4096 ] || return 1
    cp "$target" "$shared_original"
    printf '# Generated by nxPanel. Shared country lookup.\n# GeoIP2 is not loaded.\n' > "$shared_candidate"
    same_content "$shared_original" "$shared_candidate" && return 0
    mmdb=$(sed -n '2s/^geoip2 "\(\/[^"$\\]*\)" {$/\1/p' "$shared_original")
    [ -n "$mmdb" ] || return 1
    {
        printf '# Generated by nxPanel. Shared country lookup.\ngeoip2 "%s" {\n' "$mmdb"
        cat <<'EOF'
    $nxpanel_geoip_country_raw source=$remote_addr country iso_code;
    $nxpanel_geoip_registered_raw source=$remote_addr registered_country iso_code;
}
map $nxpanel_geoip_registered_raw $nxpanel_geoip_registered {
    ~^[A-Za-z][A-Za-z]$ $nxpanel_geoip_registered_raw;
    default ZZ;
}
map $nxpanel_geoip_country_raw $nxpanel_geoip_country {
    ~^[A-Za-z][A-Za-z]$ $nxpanel_geoip_country_raw;
    default $nxpanel_geoip_registered;
}
EOF
    } | same_content - "$shared_original" || return 1
    shared=$target
}

uninstall_module "$@"
